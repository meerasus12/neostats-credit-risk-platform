# ============================================================
# RULE-BASED QUERY SYSTEM
# ============================================================

def rule_based_question(question):

    question = question.lower().strip()


    # ========================================================
    # QUERY 1 - DEFAULTED APPLICANTS
    # ========================================================

    if (
        "defaulted applicants" in question
        or "applicants defaulted" in question
        or "number of defaults" in question
        or "defaulted" in question
    ):

        sql = """
        SELECT COUNT(*) AS defaulted_applicants
        FROM application_train
        WHERE TARGET = 1;
        """

        result = run_query(sql)

        total = int(
            result[
                "defaulted_applicants"
            ].iloc[0]
        )

        return (
            f"There are {total:,} "
            f"defaulted applicants."
        )


    # ========================================================
    # QUERY 2 - NON-DEFAULTED APPLICANTS
    # ========================================================

    elif (
        "non-defaulted applicants" in question
        or "non defaulted applicants" in question
        or "did not default" in question
        or "not default" in question
        or "non default" in question
    ):

        sql = """
        SELECT COUNT(*) AS non_defaulted_applicants
        FROM application_train
        WHERE TARGET = 0;
        """

        result = run_query(sql)

        total = int(
            result[
                "non_defaulted_applicants"
            ].iloc[0]
        )

        return (
            f"There are {total:,} "
            f"non-defaulted applicants."
        )


    # ========================================================
    # QUERY 3 - TOTAL APPLICANTS
    # ========================================================

    elif (
        "how many applicants" in question
        or "total applicants" in question
        or "number of applicants" in question
    ):

        sql = """
        SELECT COUNT(*) AS total_applicants
        FROM application_train;
        """

        result = run_query(sql)

        total = int(
            result[
                "total_applicants"
            ].iloc[0]
        )

        return (
            f"There are "
            f"{total:,} "
            f"applicants in the dataset."
        )


    # ========================================================
    # QUERY 4 - AVERAGE INCOME
    # ========================================================

    elif (
        "average income" in question
        or "average applicant income" in question
        or "mean income" in question
    ):

        sql = """
        SELECT AVG(AMT_INCOME_TOTAL) AS average_income
        FROM application_train;
        """

        result = run_query(sql)

        average = float(
            result[
                "average_income"
            ].iloc[0]
        )

        return (
            f"The average applicant "
            f"income is {average:,.2f}."
        )


    # ========================================================
    # QUERY 5 - AVERAGE CREDIT
    # ========================================================

    elif (
        "average credit" in question
        or "average credit amount" in question
        or "mean credit" in question
    ):

        sql = """
        SELECT AVG(AMT_CREDIT) AS average_credit
        FROM application_train;
        """

        result = run_query(sql)

        average = float(
            result[
                "average_credit"
            ].iloc[0]
        )

        return (
            f"The average credit "
            f"amount is {average:,.2f}."
        )


    return None


# ============================================================
# MAIN NL-TO-SQL PIPELINE
# ============================================================

def answer_question(question):
    """
    Main natural-language query pipeline.

    1. Check known safe query patterns.
    2. If no pattern matches, use the LLM.
    3. Include conversation memory in the LLM prompt.
    4. Validate generated SQL.
    5. Execute SQL.
    6. Generate a business-friendly answer.
    """

    if not question:

        return "Please enter a question."


    # ========================================================
    # STEP 1 - SAFE EXISTING PATTERNS
    # ========================================================

    rule_answer = rule_based_question(
        question
    )


    if rule_answer is not None:

        return rule_answer


    # ========================================================
    # STEP 2 - LLM SQL GENERATION
    # ========================================================

    try:

        sql = generate_sql_with_llm(
            question
        )


        print()
        print("Generated SQL:")
        print(sql)


        # ====================================================
        # STEP 3 - SQL VALIDATION
        # ====================================================

        is_valid, validation_result = validate_sql(
            sql
        )


        if not is_valid:

            print(
                "SQL validation failed:",
                validation_result
            )

            return (
                "I could not safely process "
                "that question."
            )


        validated_sql = validation_result


        # ====================================================
        # STEP 4 - UNSUPPORTED QUESTION
        # ====================================================

        if (
            "UNSUPPORTED"
            in validated_sql.upper()
        ):

            return (
                "Sorry, I cannot answer that "
                "question using the available "
                "credit dataset."
            )


        # ====================================================
        # STEP 5 - EXECUTE SQL
        # ====================================================

        result = run_query(
            validated_sql
        )


        # ====================================================
        # STEP 6 - BUSINESS ANSWER
        # ====================================================

        answer = generate_business_answer(

            question,

            validated_sql,

            result

        )


        return answer


    except Exception as e:

        print(
            "LLM processing error:",
            str(e)
        )

        return (
            "I was unable to process that "
            "question using the LLM. "
            "Please try again."
        )


