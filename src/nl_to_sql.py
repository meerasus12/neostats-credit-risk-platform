# BUSINESS ANSWER GENERATION
# ============================================================

def generate_business_answer(
    question,
    sql,
    result
):
    """
    Convert SQL results into a readable business answer.
    """

    result_text = result.to_string(
        index=False
    )


    # --------------------------------------------------------
    # Build business answer prompt
    # --------------------------------------------------------

    prompt = build_business_answer_prompt(

        question,

        sql,

        result_text

    )


    # --------------------------------------------------------
    # Call LLM
    # --------------------------------------------------------

    response = client.chat.completions.create(

        model=LLM_MODEL,

        messages=[

            {
                "role": "system",
                "content": prompt
            }

        ],

        temperature=0

    )


    return response.choices[0].message.content.strip()


