# ============================================================
# DATABASE FUNCTIONS
# ============================================================

def run_query(sql):
    """
    Execute a SQL query and return the result.
    """

    connection = sqlite3.connect(
        DATABASE_PATH
    )

    try:

        result = pd.read_sql_query(
            sql,
            connection
        )

        return result

    finally:

        connection.close()


# ============================================================
# DATABASE SCHEMA
# ============================================================

def get_database_schema():
    """
    Retrieve the schema of the application_train table.
    """

    connection = sqlite3.connect(
        DATABASE_PATH
    )

    try:

        cursor = connection.cursor()

        cursor.execute(
            "PRAGMA table_info(application_train);"
        )

        columns = cursor.fetchall()

        schema = []

        for column in columns:

            column_name = column[1]
            column_type = column[2]

            schema.append(
                f"{column_name} ({column_type})"
            )

        return ", ".join(schema)

    finally:

        connection.close()


# ============================================================
# SQL VALIDATION
# ============================================================

def validate_sql(sql):
    """
    Validate SQL generated by the LLM.

    Only SELECT queries using application_train
    are permitted.
    """

    if not sql:

        return False, "SQL query is empty."


    # --------------------------------------------------------
    # Remove markdown code fences
    # --------------------------------------------------------

    sql = sql.replace(
        "```sql",
        ""
    )

    sql = sql.replace(
        "```",
        ""
    )

    sql = sql.strip()


    # --------------------------------------------------------
    # Must start with SELECT
    # --------------------------------------------------------

    if not re.match(
        r"^\s*SELECT\b",
        sql,
        re.IGNORECASE
    ):

        return False, (
            "Only SELECT queries are allowed."
        )


    # --------------------------------------------------------
    # Forbidden operations
    # --------------------------------------------------------

    forbidden_keywords = [

        "INSERT",
        "UPDATE",
        "DELETE",
        "DROP",
        "ALTER",
        "CREATE",
        "REPLACE",
        "TRUNCATE",
        "ATTACH",
        "DETACH",
        "PRAGMA"

    ]


    for keyword in forbidden_keywords:

        if re.search(
            rf"\b{keyword}\b",
            sql,
            re.IGNORECASE
        ):

            return False, (
                f"Forbidden SQL operation detected: "
                f"{keyword}"
            )


    # --------------------------------------------------------
    # Only application_train table is allowed
    # --------------------------------------------------------

    tables = re.findall(
        r"\b(?:FROM|JOIN)\s+([A-Za-z_][A-Za-z0-9_]*)",
        sql,
        re.IGNORECASE
    )


    for table in tables:

        if table.lower() != "application_train":

            return False, (
                "Only the application_train table "
                "is allowed."
            )


    return True, sql


# ============================================================
# LLM SQL GENERATION WITH CONVERSATION MEMORY
# ============================================================

def generate_sql_with_llm(question):
    """
    Generate SQL using the LLM.

    Previous conversation is included in the prompt so
    contextual questions can be understood.
    """

    # --------------------------------------------------------
    # Get database schema
    # --------------------------------------------------------

    schema = get_database_schema()


    # --------------------------------------------------------
    # Get conversation memory
    # --------------------------------------------------------

    conversation = get_memory_text()


    # --------------------------------------------------------
    # Build prompt
    # --------------------------------------------------------

    prompt = build_sql_prompt(

        question,

        schema,

        conversation

    )


    print()
    print("Conversation context sent to LLM:")
    print(conversation)


    # --------------------------------------------------------
    # Call LLM
    # --------------------------------------------------------

    response = client.chat.completions.create(

        model=LLM_MODEL,

        messages=[

            {
                "role": "system",
                "content": prompt
            }

        ],

        temperature=0

    )


    # --------------------------------------------------------
    # Get SQL
    # --------------------------------------------------------

    sql = response.choices[0].message.content.strip()


    # --------------------------------------------------------
    # Remove markdown if returned
    # --------------------------------------------------------

    sql = sql.replace(
        "```sql",
        ""
    )

    sql = sql.replace(
        "```",
        ""
    )

    sql = sql.strip()


    return sql


